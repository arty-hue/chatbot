export interface StressResult {
  status: string;
  color: string;
  advice: string;
  level: number; // 0-100 for progress bar
}

export function checkStress(voltage: string): StressResult | null {
  const v = parseFloat(voltage);
  if (isNaN(v)) return null;

  if (v >= 120) {
    return {
      status: "ปกติ (ไม่เครียด)",
      color: "#22c55e",
      advice: "✅ ต้นพริกแข็งแรงดี พืชอยู่ในสภาพไม่เครียด การเจริญเติบโตปกติ",
      level: 100
    };
  } else if (v >= 100) {
    return {
      status: "ปกติ",
      color: "#84cc16",
      advice: "🟢 พริกอยู่ในสภาพปกติ ควรดูแลรักษารดน้ำใส่ปุ๋ยตามแนวทางมาตรฐาน",
      level: 80
    };
  } else if (v >= 70) {
    return {
      status: "เริ่มมีความเครียดเล็กน้อย",
      color: "#eab308",
      advice: "⚠️ พริกเริ่มมีความเครียด ควรตรวจสอบความชื้นในดิน การให้น้ำ และสภาพอากาศ",
      level: 60
    };
  } else if (v >= 40) {
    return {
      status: "มีความเครียด",
      color: "#f97316",
      advice: "🟠 พริกมีความเครียด! ควรปรับการให้น้ำ (อาจมากหรือน้อยไป) และลดความร้อน/แสงแดดจัด เสริมธาตุอาหาร",
      level: 40
    };
  } else {
    return {
      status: "ความเครียดสูง (วิกฤต)",
      color: "#ef4444",
      advice: "🚨 พริกมีความเครียดมาก! เสี่ยงชะงักการเติบโตและเกิดโรค ต้องรีบฟื้นฟูทันที ตรวจสอบระบบรากและความชื้นด่วน",
      level: 20
    };
  }
}
